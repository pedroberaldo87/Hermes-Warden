"""Native dialogs and clipboard on the machine running the broker (macOS only).

Used when no Hermes Desktop window answers a prompt: for example when the request
comes from Telegram or the CLI. The typed value goes from ``osascript``'s stdout
straight into the broker process; it is never written to disk or logged.

No ``tell application "System Events"``: that would need an Automation permission prompt.
Strings are passed to AppleScript through ``argv`` (``on run argv``), never spliced
into the script source, so a title cannot inject AppleScript.
"""
from __future__ import annotations

import os
import subprocess
import sys

_ASK = r'''
on run argv
  set theTitle to item 1 of argv
  set thePrompt to item 2 of argv
  set isHidden to (item 3 of argv) is "1"
  set okLabel to item 4 of argv
  set cancelLabel to item 5 of argv
  activate
  if isHidden then
    set r to display dialog thePrompt default answer "" with hidden answer with title theTitle ¬
      buttons {cancelLabel, okLabel} default button okLabel cancel button cancelLabel with icon caution
  else
    set r to display dialog thePrompt default answer "" with title theTitle ¬
      buttons {cancelLabel, okLabel} default button okLabel cancel button cancelLabel with icon note
  end if
  return text returned of r
end run
'''

_CONFIRM = r'''
on run argv
  set theTitle to item 1 of argv
  set theMessage to item 2 of argv
  set okLabel to item 3 of argv
  set cancelLabel to item 4 of argv
  activate
  set r to display dialog theMessage with title theTitle buttons {cancelLabel, okLabel} ¬
    default button cancelLabel cancel button cancelLabel with icon caution
  return button returned of r
end run
'''


def available() -> bool:
    """macOS with a GUI session; HERMES_WARDEN_NO_HOST=1 turns host dialogs off (tests, headless)."""
    return sys.platform == "darwin" and os.environ.get("HERMES_WARDEN_NO_HOST") != "1"


def host_env() -> dict[str, str]:
    """The minimum a macOS helper needs, never the Hermes environment."""
    keys = ("PATH", "HOME", "TMPDIR", "LANG", "USER", "LOGNAME", "SHELL")
    env = {k: os.environ[k] for k in keys if k in os.environ}
    env.setdefault("PATH", "/usr/bin:/bin:/usr/sbin:/sbin")
    return env


def _osascript(script: str, args: list[str], timeout: float) -> tuple[int, str]:
    try:
        proc = subprocess.run(
            ["/usr/bin/osascript", "-", *args], input=script.encode(), capture_output=True,
            env=host_env(), timeout=timeout,
        )
    except (OSError, subprocess.TimeoutExpired):
        return 124, ""
    return proc.returncode, proc.stdout.decode("utf-8", "replace").rstrip("\n")


def ask(title: str, prompt: str, *, hidden: bool = True, ok: str = "OK", cancel: str = "Cancel",
        timeout: float = 180) -> str | None:
    """Show a (masked) input dialog; return the text, or None when cancelled/unavailable."""
    if not available():
        return None
    rc, out = _osascript(_ASK, [title, prompt, "1" if hidden else "0", ok, cancel], timeout)
    if rc != 0:
        return None
    return out


def confirm(title: str, message: str, *, ok: str = "Confirm", cancel: str = "Cancel",
            timeout: float = 180) -> bool:
    if not available():
        return False
    rc, out = _osascript(_CONFIRM, [title, message, ok, cancel], timeout)
    return rc == 0 and out == ok


_JXA_COPY = r"""
ObjC.import('AppKit');
function run(argv) {
  var data = $.NSFileHandle.fileHandleWithStandardInput.readDataToEndOfFile;
  var text = $.NSString.alloc.initWithDataEncoding(data, $.NSUTF8StringEncoding);
  var pb = $.NSPasteboard.generalPasteboard;
  pb.clearContents;
  pb.setStringForType(text, $.NSPasteboardTypeString);
  // Tell clipboard managers and Universal Clipboard not to keep it.
  pb.setStringForType($(''), 'org.nspasteboard.ConcealedType');
  pb.setStringForType($(''), 'org.nspasteboard.TransientType');
  pb.setStringForType($(''), 'org.nspasteboard.AutoGeneratedType');
  return String(pb.changeCount);
}
"""

_JXA_CLEAR = r"""
ObjC.import('AppKit');
function run(argv) {
  delay(Number(argv[1]));
  var pb = $.NSPasteboard.generalPasteboard;
  if (String(pb.changeCount) === argv[0]) { pb.clearContents; }
  return '';
}
"""


def copy(value: str, clear_after: float = 30) -> bool:
    """Copy *value* to the host clipboard (marked concealed/transient).

    A detached helper clears it after *clear_after* seconds if nothing else was copied
    since, so the clearing survives the broker exiting.
    """
    if not available():
        return False
    try:
        proc = subprocess.run(["/usr/bin/osascript", "-l", "JavaScript", "-e", _JXA_COPY],
                              input=value.encode(), capture_output=True, env=host_env(), timeout=10)
    except (OSError, subprocess.SubprocessError):
        return False
    stamp = proc.stdout.decode().strip()
    if proc.returncode != 0 or not stamp.isdigit():
        return False
    if clear_after and clear_after > 0:
        try:
            subprocess.Popen(["/usr/bin/osascript", "-l", "JavaScript", "-e", _JXA_CLEAR, stamp,
                              str(int(clear_after))], stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                             stderr=subprocess.DEVNULL, env=host_env(), start_new_session=True)
        except OSError:
            pass
    return True


def notify(title: str, message: str) -> None:
    if not available():
        return
    script = 'on run argv\ndisplay notification (item 2 of argv) with title (item 1 of argv)\nend run'
    _osascript(script, [title, message], 10)
